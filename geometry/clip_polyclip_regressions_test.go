// Regression tests for polyclip-go's known bugs. Each test uses the exact
// (or closely-analogous) inputs from the polyclip-go issue tracker and
// asserts that gobi's Martinez-Rueda implementation produces the
// geometrically-correct result — i.e. does NOT hit the same bug.
//
// The paired polyclip_regressions_bench.go under benchmarks/gobi/ runs
// polyclip-go on the same inputs so callers can confirm the bugs still
// reproduce there.

// TestBoolean_PolyclipIssue3_FourTouchingRects reproduces
// https://github.com/akavel/polyclip-go/issues/3
//
// Inputs: a single 1×1 rectangle unioned with a "clipping" made of three
// 1×1 rectangles that together tile a 2×2 square with the subject. The
// bug in polyclip-go drops the upper-right rectangle from the output.
// The correct result is a 2×2 square with area 4.
func TestBoolean_PolyclipIssue3_FourTouchingRects(t *testing.T) {
	subject := SimplePolygon([]Point{
		pt(1, 1), pt(2, 1), pt(2, 2), pt(1, 2), pt(1, 1),
	}, CRS{})
	// The upstream test uses a single polyclip.Polygon with three
	// contours. gobi's closest equivalent is a MultiPolygon with three
	// component polygons.
	clipping := MultiPolygon{
		Polygons: []Polygon{
			SimplePolygon([]Point{pt(2, 1), pt(3, 1), pt(3, 2), pt(2, 2), pt(2, 1)}, CRS{}),
			SimplePolygon([]Point{pt(1, 2), pt(2, 2), pt(2, 3), pt(1, 3), pt(1, 2)}, CRS{}),
			SimplePolygon([]Point{pt(2, 2), pt(3, 2), pt(3, 3), pt(2, 3), pt(2, 2)}, CRS{}),
		},
	}

	got, err := Union(subject, clipping)
	if err != nil {
		t.Fatalf("Union: %v", err)
	}
	area := 0.0
	switch v := got.(type) {
	case Polygon:
		area = polyPlanarArea(v)
	case MultiPolygon:
		for _, p := range v.Polygons {
			area += polyPlanarArea(p)
		}
	default:
		t.Fatalf("unexpected result type %T", got)
	}
	// Correct union area is 4 (a 2×2 square). polyclip-go returns a
	// polygon missing the upper-right rectangle, area 3.
	if !nearlyEqual(area, 4, 1e-9) {
		t.Errorf("Union area = %v, want 4 (polyclip-go issue #3 bug: returns 3)", area)
	}
}

// TestBoolean_PolyclipIssue8_ExactPolygons reproduces the exact 227-point
// inner + 27-point outer polygons from
// https://github.com/akavel/polyclip-go/issues/8 . polyclip-go returns
// an empty result even though the inner polygon is fully contained
// within the outer; the correct intersection is the inner polygon
// itself.
func TestBoolean_PolyclipIssue8_ExactPolygons(t *testing.T) {
	inner := SimplePolygon(closeRing(polyclipIssue8Inner()), CRS{})
	outer := SimplePolygon(closeRing(polyclipIssue8Outer()), CRS{})
	innerArea := polyPlanarArea(inner)

	got, err := Clip(inner, outer)
	if err != nil {
		t.Fatalf("Clip: %v", err)
	}
	gotArea := 0.0
	switch v := got.(type) {
	case Polygon:
		gotArea = polyPlanarArea(v)
	case MultiPolygon:
		for _, p := range v.Polygons {
			gotArea += polyPlanarArea(p)
		}
	default:
		t.Fatalf("unexpected result type %T", got)
	}
	// Since inner ⊂ outer, intersection area should equal inner area.
	// polyclip-go bug: returns empty geometry (area 0).
	if !nearlyEqual(gotArea, innerArea, innerArea*1e-6) {
		t.Errorf("Clip area = %v, want %v (polyclip-go issue #8 bug: returns 0)", gotArea, innerArea)
	}
}

// closeRing appends the first point to the end if the ring isn't already
// closed. gobi's SimplePolygon expects a closed ring.
func closeRing(pts []Point) []Point {
	if len(pts) < 2 {
		return pts
	}
	first, last := pts[0], pts[len(pts)-1]
	if first.X == last.X && first.Y == last.Y {
		return pts
	}
	out := make([]Point, len(pts)+1)
	copy(out, pts)
	out[len(pts)] = first
	return out
}

